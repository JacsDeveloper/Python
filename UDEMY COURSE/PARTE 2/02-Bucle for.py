# Crear lista de frutas
frutas = ["Manzana", "Banana", "Cereza", "Durazno", "Uva"]
contador = 0

# Iterar sobre la lista de frutas
for fruta in frutas:
    contador += 1
    print(f"Fruta No. {contador}: {fruta}")

# Crear lista de números
numeros = [1, 2, 3, 4, 5]

# Iterar sobre la lista de números
for numero in numeros:
    cuadrado = numero ** 2
    print(f"El cuadrado del número {numero} es: {cuadrado}")